values = [float(line) for line in data_str.strip().splitlines()]
values_np = np.array(values)

# Wrap starting at index
start_idx = 129
wrapped_values = np.concatenate([values_np[start_idx:], values_np[:start_idx]])
wrapped_indices = np.arange(len(wrapped_values))

FS = 50
MIN_DISTANCE = int(0.4 * FS)

py_peaks, _ = find_peaks(wrapped_values, distance=MIN_DISTANCE)

# Example peaks from C++ (for comparison)
cpp_peaks = np.array([28,62,98,138,178,216,252])

distances_samples = np.diff(py_peaks)
distances_seconds = distances_samples / FS

average_distance_seconds = np.mean(distances_seconds)
bpm = 60 / average_distance_seconds

print("Python peaks:", py_peaks)
print("C++ peaks:", cpp_peaks)
print("Distances between beats (seconds):", distances_seconds)
print(f"Average distance between beats: {average_distance_seconds:.3f} seconds")
print(f"Estimated Heart Rate: {bpm:.2f} BPM")

plt.figure(figsize=(15,5))
plt.plot(wrapped_indices, wrapped_values, color='blue', linewidth=2, label='Sensor Data')
plt.plot(py_peaks, wrapped_values[py_peaks], 'ro', label='Python Peaks')
plt.plot(cpp_peaks, wrapped_values[cpp_peaks], 'gx', label='C++ Peaks', markersize=10)
plt.title(f"Detected Heartbeats")
plt.xlabel("Sample Index (wrapped)")
plt.ylabel("Sensor Value")
plt.grid(True)
plt.legend()
